def _build_kk_mode_operators(sig, f_idx, level_zero=False):
    """Linearised 5D Einstein operator E, gauge map P, and divergence map Dv for one KK level on flat M_4 x [0, pi L_0]."""
    D = len(sig)
    macro = [i for i in range(D) if i != f_idx]
    space = [i for i in macro if sig[i] > 0]
    time1 = [i for i in macro if sig[i] < 0][0]

    X = sp.symbols(f'X0:{D}', real=True)
    y = X[f_idx]
    w, q, Phi0 = sp.symbols('omega q Phi0', positive=True)
    kv = sp.symbols('k1:4', real=True)
    eta = sp.diag(*[(-Phi0**2 if i == f_idx else sp.Integer(s)) for i, s in enumerate(sig)])
    eta_inv = eta.inv()

    phase = sp.exp(sp.I * (sum(kv[j] * X[space[j]] for j in range(3)) - w * X[time1]))
    C, S = (sp.Integer(1), sp.Integer(0)) if level_zero else (sp.cos(q * y), sp.sin(q * y))

    a = {(m, n): sp.Symbol(f'a_{m}{n}') for i, m in enumerate(macro) for n in macro[i:]}
    b = {m: sp.Symbol(f'b_{m}') for m in macro}
    c = sp.Symbol('c_yy')
    amps = [a[k_] for k_ in sorted(a)] + ([] if level_zero else [b[m] for m in macro]) + [c]

    h = sp.zeros(D, D)
    for (m, n), s_a in a.items():
        h[m, n] = h[n, m] = s_a * C * phase
    if not level_zero:
        for m in macro:
            h[m, f_idx] = h[f_idx, m] = b[m] * S * phase
    h[f_idx, f_idx] = c * C * phase

    dh = [[[sp.diff(h[A_i, B_i], X[C_i]) for C_i in range(D)] for B_i in range(D)] for A_i in range(D)]
    G1 = [[[sp.Rational(1, 2) * eta_inv[C_i, C_i] * (dh[C_i][B_i][A_i] + dh[C_i][A_i][B_i] - dh[A_i][B_i][C_i])
            for B_i in range(D)] for A_i in range(D)] for C_i in range(D)]
    R1 = sp.zeros(D, D)
    for A_i in range(D):
        for B_i in range(D):
            R1[A_i, B_i] = sum(sp.diff(G1[C_i][A_i][B_i], X[C_i]) for C_i in range(D)) \
                - sp.diff(sum(G1[C_i][A_i][C_i] for C_i in range(D)), X[B_i])
    Rs = sum(eta_inv[A_i, A_i] * R1[A_i, A_i] for A_i in range(D))
    dG = (R1 - sp.Rational(1, 2) * eta * Rs).applyfunc(sp.expand)

    slots = [(m, n) for (m, n) in sorted(a)] + ([] if level_zero else [(m, f_idx) for m in macro]) + [(f_idx, f_idx)]

    def strip(expr, odd):
        """Divide out the mode profile term by term (no simplify call); fails if the Z_2 parity is not the expected one."""
        prof = (S if odd else C) * phase
        val = sp.expand(sp.expand(expr) / prof)
        if val.has(y) or any(val.has(x_) for x_ in X):
            val = sp.expand(sp.simplify(val))
        if val.has(y) or any(val.has(x_) for x_ in X):
            raise AssertionError(f"KK mode profile mismatch: {val}")
        return val

    rows = [strip(dG[A_i, B_i], odd=((A_i == f_idx) ^ (B_i == f_idx))) for (A_i, B_i) in slots]
    E = sp.Matrix([[sp.diff(r_e, s_e) for s_e in amps] for r_e in rows])

    e = {m: sp.Symbol(f'e_{m}') for m in macro}
    f_y = sp.Symbol('f_y')
    gpar = [e[m] for m in macro] + ([] if level_zero else [f_y])
    xi = [sp.Integer(0)] * D
    for m in macro:
        xi[m] = e[m] * C * phase
    if not level_zero:
        xi[f_idx] = f_y * S * phase
    dh_g = sp.Matrix(D, D, lambda A_i, B_i: sp.diff(xi[B_i], X[A_i]) + sp.diff(xi[A_i], X[B_i]))
    grow = [strip(dh_g[A_i, B_i], odd=((A_i == f_idx) ^ (B_i == f_idx))) for (A_i, B_i) in slots]
    P = sp.Matrix([[sp.diff(r_g, s_g) for s_g in gpar] for r_g in grow])

    # divergence map: d^A dG_AB (contracted linearised Bianchi identity)
    T_div = sp.zeros(D, D)
    tsym = {}
    for (A_i, B_i) in slots:
        tsym[(A_i, B_i)] = sp.Symbol(f't_{A_i}{B_i}')
        odd_ab = (A_i == f_idx) ^ (B_i == f_idx)
        T_div[A_i, B_i] = T_div[B_i, A_i] = tsym[(A_i, B_i)] * (S if odd_ab else C) * phase
    out_slots = macro + ([] if level_zero else [f_idx])
    drow = [strip(sum(eta_inv[A_i, A_i] * sp.diff(T_div[A_i, B_i], X[A_i]) for A_i in range(D)), odd=(B_i == f_idx)) for B_i in out_slots]
    Dv = sp.Matrix([[sp.diff(r_d, tsym[s_d]) for s_d in slots] for r_d in drow])

    p_sq = -w**2 + sum(k_**2 for k_ in kv) - (0 if level_zero else q**2 / Phi0**2)
    info = dict(w=w, q=q, Phi0=Phi0, k=kv, amps=amps, slots=slots, macro=macro, space=space, time1=time1,
                f_idx=f_idx, p_sq=p_sq, n_a=len(a), eta=eta, a=a)
    return E, P, Dv, info



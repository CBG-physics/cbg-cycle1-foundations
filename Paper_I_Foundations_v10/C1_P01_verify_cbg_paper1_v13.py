    #      ds^2 = -N^2 dt^2 - Phi_inf^2 e^(2 psi) dt2^2 + a^2 [dr^2/(1 - k r^2) + r^2 dOmega^2], Theta = Theta(t).
    t, t2c, rc, thc, phc = sp.symbols('t t2 r_c theta phi', real=True)
    k_c = sp.Symbol('k', real=True)
    Phi_inf_s = sp.Symbol('Phi_inf', positive=True)
    N_f, a_f, psi_t, Theta_t = sp.Function('N')(t), sp.Function('a')(t), sp.Function('psi')(t), sp.Function('Theta')(t)
    da, dpsi_t, dTh = sp.diff(a_f, t), sp.diff(psi_t, t), sp.diff(Theta_t, t)
    g_flrw = sp.diag(-N_f**2, -Phi_inf_s**2 * sp.exp(2 * psi_t), a_f**2 / (1 - k_c * rc**2), a_f**2 * rc**2, a_f**2 * rc**2 * sp.sin(thc)**2)
    geo_flrw = Geometry(g_flrw, [t, t2c, rc, thc, phc], N_f * Phi_inf_s * sp.exp(psi_t) * a_f**3 * rc**2 * sp.sin(thc) / sp.sqrt(1 - k_c * rc**2))
    A_mini = sp.simplify(1 / (-geo_flrw.ginv[0, 0] * dTh**2))
    assert_zero(A_mini - N_f**2 / dTh**2, "[metric-first] FLRW khronon norm (-g^{tt} Theta'^2)^{-1} minus N^2/Theta'^2")
    V_mini = sp.Function('V_m')(psi_t, A_mini)
    L_full = N_f * a_f**3 * sp.exp(psi_t) * (geo_flrw.R - 2 * V_mini)                          # sqrt|g5| (R5 - 2V) per unit comoving coordinate volume
    L_mini = a_f * sp.exp(psi_t) * (-6 * da**2 / N_f - 6 * a_f * da * dpsi_t / N_f + 6 * k_c * N_f - 2 * a_f**2 * N_f * V_mini)
    L_diff = sp.simplify(L_full - L_mini)
    for q_f, q_name in [(N_f, "N"), (a_f, "a"), (psi_t, "psi")]:
        assert_zero(sp.simplify(euler_lagrange(L_diff, q_f, t)),
                    f"[metric-first] Theorem 8.1: sqrt|g5|(R5 - 2V) minus manuscript L_mini is a total derivative (Euler-Lagrange operator in {q_name} annihilates it)")

    E_N, E_a = euler_lagrange(L_mini, N_f, t), euler_lagrange(L_mini, a_f, t)
    E_psi, E_Theta = euler_lagrange(L_mini, psi_t, t), euler_lagrange(L_mini, Theta_t, t)
    assert_zero(sp.simplify(dTh * E_Theta - N_f * sp.diff(E_N, t) + da * E_a + dpsi_t * E_psi),
                "Theorem 8.1(a): time-reparametrisation Noether identity Theta' E_Theta - N dE_N/dt + a' E_a + psi' E_psi (Eq. 75)")

    # Hamiltonian constraint with the full V(psi, A): the lapse variation produces V + 2 A d_A V (Theorem 8.1(c), Eq. 76)
    H_s, dpsi_s, a_s, psi_sym, rho_s, dda_s, ddpsi_s = sp.symbols('H dpsi a psi_sym rho_r dda ddpsi', real=True)
    Vm_s, VmA_s = sp.symbols('Vm_s VmA_s', real=True)
    E_N_gauge = E_N.subs(dTh, 1).subs(N_f, 1).doit().subs({da: H_s * a_s, dpsi_t: dpsi_s}).subs({a_f: a_s, psi_t: psi_sym})
    is_dA_slot = lambda e: isinstance(e, sp.Subs) and isinstance(e.expr, sp.Derivative) and e.expr.args[0].args[1] == e.variables[0]
    assert_true(all(is_dA_slot(e) for e in E_N_gauge.atoms(sp.Subs)) and len(E_N_gauge.atoms(sp.Subs)) == 1,
                "Lapse variation of V(psi, N^2/Theta'^2) produces a single chain-rule term: the derivative in the khronon slot")
    E_N_gauge = E_N_gauge.replace(is_dA_slot, lambda e: VmA_s).subs(sp.Function('V_m')(psi_sym, 1), Vm_s)
    C_full = sp.simplify(E_N_gauge / (2 * a_s**3 * sp.exp(psi_sym)))
    assert_zero(C_full - (3 * (H_s**2 + k_c / a_s**2 + H_s * dpsi_s) - (Vm_s + 2 * VmA_s)),
                "Theorem 8.1(c): E_N/(2 a^3 e^psi) at N = Theta' = 1 minus [3(H^2 + k/a^2 + H psi') - (V + 2 A d_A V)] (lapse term of Eq. 76)")

    # Symmetric criticality on the FLRW sector: Euler-Lagrange equations of the reduced action = 5D field equations.
    # Hilbert stress of ell = -2 V(psi, A) with psi = -(1/2) ln(-g^{22} Phi_inf^2), A = (-g^{tt} Theta'^2)^{-1}:
    qt_f, q2_f, qs_f = sp.symbols('qt_f q2_f qs_f', real=True, nonzero=True)
    V_head_f = sp.Function('V_m')
    V_q = V_head_f(-sp.Rational(1, 2) * sp.log(-q2_f * Phi_inf_s**2), 1 / (-qt_f * dTh**2))
    VmP_s = sp.Symbol('VmP_s', real=True)
    ln_sq_f = -sp.Rational(1, 2) * sp.log(qt_f * q2_f * qs_f**3)
    T_flrw = {}
    for name_q, var_q, mult_q in (("t", qt_f, 1), ("2", q2_f, 1), ("x", qs_f, 3)):
        el_q = sp.diff(-2 * V_q, var_q) / mult_q + (-2 * V_q) * sp.diff(ln_sq_f, var_q) / mult_q
        el_q = el_q.subs(V_q.fdiff(1), VmP_s).subs(V_q.fdiff(2), VmA_s).subs(V_q, Vm_s)
        T_flrw[name_q] = sp.simplify((-var_q * el_q).subs({qt_f: geo_flrw.ginv[0, 0], q2_f: geo_flrw.ginv[1, 1]}))
    assert_zero(T_flrw["t"] - (-Vm_s - 2 * A_mini * VmA_s), "[Hilbert] FLRW T^t_t minus (-V - 2 A d_A V)")
    assert_zero(T_flrw["2"] - (-Vm_s - VmP_s), "[Hilbert] FLRW T^2_2 minus (-V - d_psi V)")
    assert_zero(T_flrw["x"] + Vm_s, "[Hilbert] FLRW T^x_x minus (-V)")

    def flrw_symbols(expr):
        """N = Theta' = 1 gauge; V_m and its two partial derivatives -> symbols; a'', psi'' -> symbols."""
        expr = expr.subs(sp.diff(N_f, t), 0).subs(dTh, 1).subs(N_f, 1).doit()
        expr = expr.subs({sp.diff(a_f, t, 2): dda_s, sp.diff(psi_t, t, 2): ddpsi_s}).subs({da: H_s * a_s, dpsi_t: dpsi_s}).subs({a_f: a_s})
        V_g = sp.Function('V_m')(psi_t, 1)
        expr = expr.replace(is_dA_slot, lambda e: VmA_s).subs(sp.Derivative(V_g, psi_t), VmP_s).subs(V_g, Vm_s)
        return expr.subs(psi_t, psi_sym)

    G_flrw = geo_flrw.mixed(geo_flrw.Ein)
    sq_f = a_s**3 * sp.exp(psi_sym)
    gauge_T = lambda e: e.subs(dTh, 1).subs(N_f, 1)
    for el_expr, comp, name_c, factor_c in ((E_N, 0, "t", 2), (E_a, 2, "x", 6 / a_s), (E_psi, 1, "2", 2)):
        field_eq = flrw_symbols(G_flrw[comp, comp]) - gauge_T(T_flrw[name_c])
        assert_zero(sp.simplify(flrw_symbols(el_expr) / sq_f + factor_c * field_eq),
                    f"[symmetric criticality] FLRW sector: Euler-Lagrange equation of L_mini reproduces the 5D field equation E^{name_c}_{name_c} = G^{name_c}_{name_c} - T^{name_c}_{name_c} (N = 1 gauge)")

    # 2.5: Theorem 8.3: Friedmann system from the Euler-Lagrange equations of L_mini with V = V(psi) (truncation H8)
    #      plus the radiation test fluid L_r = -2 N rho_0/a (H8): rho_r = rho_0 a^-4 e^-psi.
    rho0_s = sp.Symbol('rho_0', positive=True)
    V_s_fn = sp.Function('V_s')(psi_t)
    L_cos = a_f * sp.exp(psi_t) * (-6 * da**2 / N_f - 6 * a_f * da * dpsi_t / N_f + 6 * k_c * N_f - 2 * a_f**2 * N_f * V_s_fn) - 2 * N_f * rho0_s / a_f
    rho_of_t = rho0_s * a_f**(-4) * sp.exp(-psi_t)
    assert_zero(sp.simplify(sp.diff(rho_of_t, t) / rho_of_t + 4 * da / a_f + dpsi_t), "Radiation test fluid: rho_r' / rho_r + (4H + psi') for rho_r = rho_0 a^-4 e^-psi [H8]", tag="D|H")

    def gauge(expr):
        expr = expr.subs(sp.diff(N_f, t), 0).subs(N_f, 1).doit()
        expr = expr.subs({sp.diff(a_f, t, 2): dda_s, sp.diff(psi_t, t, 2): ddpsi_s}).subs({da: H_s * a_s, dpsi_t: dpsi_s}).subs(a_f, a_s)
        return sp.simplify(expr.subs(rho0_s, rho_s * a_s**4 * sp.exp(psi_t)).subs(psi_t, psi_sym))

    EN_g, Ea_g, Ep_g = [gauge(euler_lagrange(L_cos, q_f, t)) for q_f in (N_f, a_f, psi_t)]
    V_s = sp.Function('V_s')(psi_sym)
    dV_s = sp.diff(V_s, psi_sym)
    sol_cos = sp.solve([Ea_g, Ep_g], (dda_s, ddpsi_s))
    dda_over_a, ddpsi_val = sp.simplify(sol_cos[dda_s] / a_s), sp.simplify(sol_cos[ddpsi_s])
    C_Fried = sp.simplify(EN_g / (2 * a_s**3 * sp.exp(psi_sym)))
    assert_zero(dda_over_a - (-H_s**2 - k_c / a_s**2 + sp.Rational(1, 3) * (V_s + dV_s)),
                "Theorem 8.3: a''/a solved from E_a = E_psi = 0 minus manuscript form -H^2 - k/a^2 + (V + V')/3 [H8]", tag="D|H")
    assert_zero(ddpsi_val - (-dpsi_s**2 - 2 * H_s * dpsi_s + H_s**2 + k_c / a_s**2 + sp.Rational(1, 3) * (V_s - rho_s - 2 * dV_s)),
                "Theorem 8.3: psi'' solved from E_a = E_psi = 0 minus manuscript form [H8]", tag="D|H")
    assert_zero(C_Fried - (3 * (H_s**2 + k_c / a_s**2 + H_s * dpsi_s) - (rho_s + V_s)),
                "Theorem 8.3: constraint E_N/(2 a^3 e^psi) minus C_Fried = 3(H^2 + k/a^2 + H psi') - (rho_r + V) [H8]", tag="D|H")
    flow = {H_s: dda_over_a - H_s**2, dpsi_s: ddpsi_val, a_s: H_s * a_s, psi_sym: dpsi_s, rho_s: -(4 * H_s + dpsi_s) * rho_s}
    dC_dt = sum(sp.diff(C_Fried, var_f) * rate_f for var_f, rate_f in flow.items())
    assert_zero(sp.simplify(dC_dt + (3 * H_s + dpsi_s) * C_Fried),
                "Theorem 8.3(ii): constraint propagation dC_Fried/dt + (3H + psi') C_Fried along the derived flow (Eq. 84) [H8]", tag="D|H")

    Vn, dVn = sp.symbols('Vn dVn', real=True)
    flat = lambda e: e.subs(dV_s, dVn).subs(V_s, Vn).subs(k_c, 0)
    CTX["cosmo_num"] = sp.lambdify((a_s, H_s, dpsi_s, rho_s, Vn, dVn), [flat(dda_over_a), flat(ddpsi_val)], "numpy")
    CTX["C_Fried_num"] = sp.lambdify((H_s, dpsi_s, rho_s, Vn), flat(C_Fried), "numpy")
    H_roots = sp.solve(flat(C_Fried), H_s)
    CTX["H_roots_num"] = [sp.lambdify((dpsi_s, rho_s, Vn), rt, "numpy") for rt in H_roots]

    # 2.6: Theorem 8.6(i): minisuperspace metric from the kinetic Hessian of L_mini (lapse stripped): L_kin = G_ij q'^i q'^j / N
    v_a, v_p = sp.symbols('v_a v_psi', real=True)
    a_m = sp.Symbol('a', positive=True)
    p_m = sp.Symbol('psi', real=True)
    L_kin = (N_f * L_mini).subs(sp.diff(N_f, t), 0).subs({da: v_a, dpsi_t: v_p}).subs({a_f: a_m, psi_t: p_m})
    G_mini = sp.Matrix(2, 2, lambda i_m, j_m: sp.simplify(sp.diff(L_kin, [v_a, v_p][i_m], [v_a, v_p][j_m]) / 2))
    assert_true(all(sp.diff(entry, N_f) == 0 for entry in G_mini), "Kinetic Hessian of N L_mini is lapse-independent (defines G_mini up to lapse rescalings)")
    det_G = sp.simplify(G_mini.det())
    assert_zero(det_G + 9 * a_m**4 * sp.exp(2 * p_m), "det G_mini + 9 a^4 e^(2 psi) in the chart (a, psi): Lorentzian signature (-,+), sqrt|G| = 3 a^2 e^psi")
    sqrtG = 3 * a_m**2 * sp.exp(p_m)
    geo_mini = Geometry(G_mini, [a_m, p_m], sqrtG)
    assert_zero(geo_mini.R, "Minisuperspace curvature R[G_mini] (flat: a curvature term xi R cannot contribute for ANY xi)")
    d_mini = sp.Integer(G_mini.shape[0])
    assert_zero((d_mini - 2) / (4 * (d_mini - 1)), "Theorem 8.6(i): conformal coupling (d - 2)/(4(d - 1)) at d = dim G_mini = 2 [standard formula, imported]", tag="D|H")
    Om_f, Psi_w = sp.Function('Omega')(a_m, p_m), sp.Function('Psi_Univ')(a_m, p_m)
    LB_0 = laplace_beltrami(G_mini, [a_m, p_m], sqrtG, Psi_w)
    LB_Om = laplace_beltrami(Om_f * G_mini, [a_m, p_m], Om_f * sqrtG, Psi_w)
    assert_zero(sp.simplify(LB_Om - LB_0 / Om_f), "Lapse-rescaling covariance in d = 2: Box[Omega G_mini] - Box[G_mini]/Omega (the WDW operator is fixed up to an overall factor)")
    U_c, W_c = a_m**2, a_m * sp.exp(p_m)
    Jac = sp.Matrix([[sp.diff(U_c, a_m), sp.diff(U_c, p_m)], [sp.diff(W_c, a_m), sp.diff(W_c, p_m)]])
    G_null = sp.Matrix([[0, -sp.Rational(3, 2)], [-sp.Rational(3, 2), 0]])
    assert_zero(sp.simplify(Jac.T * G_null * Jac - G_mini), "Null chart: G_mini minus the pull-back of -3 dU dW with U = a^2, W = a e^psi")
    rho_m, chi_m = sp.symbols('rho chi', positive=True)
    Jac_m = sp.Matrix([[sp.diff(rho_m * sp.exp(chi_m), rho_m), sp.diff(rho_m * sp.exp(chi_m), chi_m)],
                       [sp.diff(rho_m * sp.exp(-chi_m), rho_m), sp.diff(rho_m * sp.exp(-chi_m), chi_m)]])
    G_milne = sp.simplify(Jac_m.T * G_null * Jac_m)
    assert_zero(G_milne - sp.diag(-3, 3 * rho_m**2), "Milne chart U = rho e^chi, W = rho e^-chi: G_mini minus diag(-3, 3 rho^2), with rho^2 = U W = a^3 e^psi")
    f_m = sp.Function('f')(rho_m)
    p_ord = sp.Symbol('p', real=True)
    LB_radial = laplace_beltrami(G_milne, [rho_m, chi_m], 3 * rho_m, f_m)
    family = G_milne.inv()[0, 0] * rho_m**(-p_ord) * sp.diff(rho_m**p_ord * sp.diff(f_m, rho_m), rho_m)
    p_sol = sp.solve(sp.simplify(LB_radial - family).coeff(sp.diff(f_m, rho_m)), p_ord)
    assert_true(p_sol == [1], f"Theorem 8.6(i): Laplace-Beltrami radial operator on G_mini equals rho^-p d_rho(rho^p d_rho) only for p = {p_sol} (Eq. 87), rho = a^(3/2) e^(psi/2)")
    assert_zero(sp.simplify(LB_radial - family.subs(p_ord, 1)), "Theorem 8.6(i): residual of the p = 1 ordering in the Milne radial coordinate")
    print("  [NOTE] v12 typed the measure as sqrt|G| = a_tilde * Phi. The kinetic Hessian gives 3 a^2 e^psi in (a, psi) and 3 rho in the Milne chart;")
    print("         the p = 1 statement is confirmed for rho = a^(3/2) (Phi/Phi_inf)^(1/2). Align the definition of a_tilde in Eq. (87) with this chart.")

    # 2.7: Node A: Tensor gravitational-wave speed c_T = 1, kinetic sign +(1/2) h_t^2 & Hubble-dilaton friction 3H + psi' on 5D FLRW
    x_gw, y_gw, z_gw = sp.symbols('x_gw y_gw z_gw', real=True)
    eps_gw = sp.Symbol('epsilon_gw', real=True)
    h_gw = sp.Function('h_gw')(t, z_gw)
    g_gw = sp.diag(-N_f**2, -Phi_inf_s**2 * sp.exp(2 * psi_t),
                   a_f**2 * sp.exp(eps_gw * h_gw), a_f**2 * sp.exp(-eps_gw * h_gw), a_f**2)
    sqrtg_gw = N_f * Phi_inf_s * sp.exp(psi_t) * a_f**3
    geo_gw = Geometry(g_gw, [t, t2c, x_gw, y_gw, z_gw], sqrtg_gw)

    assert_zero(sp.diff(geo_gw.ginv[0, 0], eps_gw),
                "[Node A] d/d eps of g^{tt} == 0 (khronon norm A is blind to the tensor mode, exactly to all orders)")
    assert_zero(sp.diff(geo_gw.ginv[1, 1], eps_gw),
                "[Node A] d/d eps of g^{22} == 0 (fiber scalar psi is blind to the tensor mode, exactly to all orders)")
    assert_zero(sp.diff(g_gw.det(), eps_gw),
                "[Node A] d/d eps of det g == 0 (measure sqrt|g5| is blind to the tensor mode, exactly to all orders)")

    G_gw_lin = geo_gw.mixed(geo_gw.Ein).applyfunc(lambda e: sp.simplify(sp.diff(e, eps_gw).subs(eps_gw, 0)))
    wave_gw = sp.expand(G_gw_lin[2, 2])
    off_gw = sp.Matrix(G_gw_lin)
    off_gw[2, 2] = off_gw[3, 3] = 0
    assert_zero(off_gw,
                "[Node A] All O(eps) components of G^A_B other than (x,x), (y,y) vanish (consistent TT truncation: no mixing with psi, A, N, a)")
    assert_zero(G_gw_lin[2, 2] + G_gw_lin[3, 3], "[Node A] O(eps): G^x_x + G^y_y == 0 (pure transverse-traceless polarisation)")

    h_t, h_tt, h_zz = sp.diff(h_gw, t), sp.diff(h_gw, t, 2), sp.diff(h_gw, z_gw, 2)
    c_tt, c_zz, c_t = wave_gw.coeff(h_tt), wave_gw.coeff(h_zz), sp.simplify(wave_gw.coeff(h_t))
    assert_zero(wave_gw - (c_tt * h_tt + c_zz * h_zz + sp.expand(c_t * h_t)),
                "[Node A] O(eps) G^x_x contains only h_tt, h_zz, h_t terms (zero mass term, zero undifferentiated h term for any V(psi, A))")
    c_T_sq = sp.simplify(-(c_zz / c_tt) * a_f**2 / N_f**2)
    assert_equal(c_T_sq, 1, "[Node A] Tensor propagation speed squared c_T^2 = -(c_zz / c_tt) a^2 / N^2 in proper units (N dt, a dz)")
    friction_gw = sp.simplify(c_t / c_tt)
    assert_zero(friction_gw - sp.diff(sp.log(a_f**3 * sp.exp(psi_t) / N_f), t),
                "[Node A] Tensor friction coefficient minus d/dt ln(a^3 e^psi / N) [= 3H + psi' at N = 1]")

    L_gw_exact = (sqrtg_gw / Phi_inf_s) * geo_gw.R
    L_gw_cand = (sqrtg_gw / Phi_inf_s) * eps_gw**2 * (h_t**2 / N_f**2 - sp.diff(h_gw, z_gw)**2 / a_f**2) / 2
    el_gw_exact = euler_equations(L_gw_exact, [h_gw], [t, z_gw])[0].lhs      # complete operator, mixed second derivatives included
    el_gw_cand = euler_equations(L_gw_cand, [h_gw], [t, z_gw])[0].lhs
    assert_zero(sp.simplify(el_gw_exact - el_gw_cand),
                "[Node A] Euler-Lagrange operator of sqrt|g5| R5 in h minus that of (eps^2/2) N a^3 e^psi [h_t^2/N^2 - h_z^2/a^2] (exact in h; healthy kinetic sign +(1/2) h_t^2)")
    print("         Scope of Node A: homogeneous khronon backgrounds, n = 0 tensor mode. The static black-hole background is not covered.")



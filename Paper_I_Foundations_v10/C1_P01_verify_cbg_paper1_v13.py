_POTENTIALS = {}


def build_potential_models():
    """V = c m^2 (psi - psi_t(A))^2 with c from the jet matrix of Module 0; derivatives generated by SymPy (no typed derivatives)."""
    if _POTENTIALS:
        return
    psi_s, A_s, m_s = sp.symbols('psi_s A_s m_s', real=True)
    Ac, pm = P0["A_crit"], P0["psi_max"]
    C_max = sp.exp(2 * pm) - 1
    u_ml = Ac**2 * (1 - A_s)**2
    kernels = {
        1: sp.log(1 + C_max * (1 - A_s)) / 2,                                   # Model 1: linear activation (comparison ansatz, H4)
        2: sp.log(1 + C_max * u_ml / (u_ml + A_s**2)) / 2,                      # Model 2: rational activation (comparison ansatz, H4)
        3: pm * (sp.exp(-(A_s / Ac)**2) - sp.exp(-(1 / Ac)**2)),                # Model 3: Gaussian kernel, Paper 0 Eq. (112) (canonical, H4)
    }
    for model_id, psi_t in kernels.items():
        V_expr = CTX["V2_coeff"] * m_s**2 * (psi_s - psi_t)**2
        outs = [V_expr, sp.diff(V_expr, psi_s), sp.diff(V_expr, A_s), psi_t, sp.diff(psi_t, A_s)]
        _POTENTIALS[model_id] = sp.lambdify((psi_s, A_s, m_s), outs, "numpy")
    CTX["psi_t3_sym"] = (kernels[3], A_s)


def _potential_model(psi, A, m_hat, model_id=3):
    V, dV_dpsi, dV_dA, psi_t, dpsi_t_dA = _POTENTIALS[model_id](psi, A, m_hat)
    return V, dV_dpsi, dV_dA, psi_t, dpsi_t_dA


def solve_frobenius_bvp(m_hat=M_HAT_REF, model_id=3, r_min=R_MIN, r_max=None, prev_sol=None, tol=1e-9):
    """
    Integrates the normal-form system DERIVED in Module 0 (lambdified) in the smooth horizon variables
    y = [A, P = (r - 1) B, psi, psi'] (units r_h = 1). Boundary data: Laurent residue b_{-1} (Module 2.2) and the
    regularity slope (pole bracket of psi'') at r_min; A B -> 1 and psi -> 0 at r_max.
    """
    nf, slope, bm1 = CTX["nf_num"], CTX["slope_num"], CTX["bm1_num"]
    if r_max is None:
        r_max = max(10.0, 25.0 / m_hat)
    s_grid = np.linspace(0.0, 1.0, 350)
    r_mesh = r_min + (r_max - r_min) * (s_grid**3)

    def ode_rhs(r, y):
        A, P, psi, dpsi = y[0], y[1], y[2], y[3]
        B = P / (r - 1.0)
        V, dV_dpsi, dV_dA, _, _ = _potential_model(psi, A, m_hat, model_id=model_id)
        dA, dB, ddpsi = nf(r, A, B, dpsi, V, dV_dpsi, dV_dA)
        return np.vstack([dA, B + (r - 1.0) * dB, dpsi, ddpsi])

    def bc(ya, yb):
        A_a, P_a, psi_a, dpsi_a = ya[0], ya[1], ya[2], ya[3]
        A_b, P_b, psi_b = yb[0], yb[1], yb[2]
        V_a, dV_dpsi_a, dV_dA_a, _, _ = _potential_model(psi_a, A_a, m_hat, model_id=model_id)
        return np.array([P_a - bm1(r_min, dpsi_a, V_a), dpsi_a - slope(r_min, A_a, V_a, dV_dpsi_a, dV_dA_a),
                         A_b * P_b / (r_max - 1.0) - 1.0, psi_b])

    if prev_sol is not None:
        y_init = prev_sol.sol(np.clip(r_mesh, prev_sol.x[0], prev_sol.x[-1]))
    else:
        A_init = 1.0 - 1.0 / r_mesh
        _, _, _, psi_t_init, _ = _potential_model(0.0, A_init, m_hat, model_id=model_id)
        psi_init = psi_t_init * np.exp(-0.3 * (r_mesh - 1.0))
        y_init = np.vstack([A_init, r_mesh.copy(), psi_init, np.gradient(psi_init, r_mesh)])

    sol = solve_bvp(ode_rhs, bc, r_mesh, y_init, tol=tol, max_nodes=100000)
    if not sol.success:
        raise RuntimeError(f"BVP failed for m_hat={m_hat}, model={model_id}: {sol.message}")
    return sol


def eval_bvp_ABpsi(sol, r_val):
    """[A(r), B(r), psi(r), psi'(r)] from the desingularised BVP solution."""
    y = sol.sol(r_val)
    return y[0], y[1] / (r_val - 1.0), y[2], y[3]


def solve_stiff_limit_bvp(r_min=1.0, r_max=60.0):
    """
    Stiff-limit BVP (m_hat -> oo, Theorem 4.6): numerical implementation of Eqs. (55)-(56), both verified symbolically
    in Module 2.3, with psi = psi_t(A) (Model 3). P = A B and B'/B = P'/P - A'/A remove all horizon poles, so the
    integration starts at the horizon r_min = 1 (A(1) = 0). The chain-rule expansion below is hand-coded numerics.
    """
    eta0 = -2.0 * PSI_MAX / A_CRIT**2

    def eta_derivs(A):
        eta = eta0 * np.exp(-(A / A_CRIT)**2)
        deta_dA = eta * (-2.0 * A / A_CRIT**2)
        return eta, deta_dA, eta * A, eta + A * deta_dA

    s_grid = np.linspace(0.0, 1.0, 400)
    r_mesh = r_min + (r_max - r_min) * (s_grid**3)

    def stiff_ode(r, y):
        A, dA = y[0], y[1]
        eta, deta_dA, pt1, pt2 = eta_derivs(A)
        psi_p = pt1 * dA
        P = A + r * dA + 2.0 * r * A * pt1 * dA + 0.5 * r**2 * A * eta * dA**2
        dP_ddA = r * (1.0 + 2.0 * A * pt1 + r * A * eta * dA)
        dP_rest = (2.0 * dA + 2.0 * A * pt1 * dA + 2.0 * r * (pt1 + A * pt2) * dA**2
                   + r * A * eta * dA**2 + 0.5 * r**2 * (eta + A * deta_dA) * dA**3)
        factor_Pprime = -(dA / (2.0 * P) + A / (r * P) + A * psi_p / P)
        coeff_ddA = 1.0 + factor_Pprime * dP_ddA + 2.0 * A * pt1
        rhs_rest = (factor_Pprime * dP_rest + 2.0 * dA / r + 2.0 * A * (pt2 + pt1**2) * dA**2 + (2.0 * A / r + 2.0 * dA) * psi_p)
        return np.vstack([dA, -rhs_rest / coeff_ddA])

    def stiff_bc(ya, yb):
        A_b, dA_b = yb[0], yb[1]
        eta_b, _, pt1_b, _ = eta_derivs(A_b)
        P_b = A_b + r_max * dA_b + 2.0 * r_max * A_b * pt1_b * dA_b + 0.5 * r_max**2 * A_b * eta_b * dA_b**2
        return np.array([ya[0], P_b - 1.0])

    sol = solve_bvp(stiff_ode, stiff_bc, r_mesh, np.vstack([1.0 - 1.0 / r_mesh, 1.0 / r_mesh**2]), tol=1e-9, max_nodes=25000)
    if not sol.success:
        raise RuntimeError(f"Stiff BVP failed: {sol.message}")
    return sol



    q1r, h_p = sp.symbols('q1r h_prime', real=True)
    A_kh = 1 / (-(q11 + 2 * q1r * h_p + qrr * h_p**2))                                       # (-g^{AB} d_A Theta d_B Theta)^{-1}
    V_kh = V_head(psi_e, A_kh)
    ln_sq_od = -sp.Rational(1, 2) * sp.log((q11 * qrr - q1r**2) * q22 * qth * qph)
    ell_od = -2 * V_kh
    T_1r_cov = -sp.Rational(1, 2) * (sp.diff(ell_od, q1r) + ell_od * sp.diff(ln_sq_od, q1r))  # factor 1/2: g^{1r} = g^{r1} vary together
    T_1r_cov = T_1r_cov.subs(V_kh.fdiff(2), VA_sy).subs(V_kh, V_sy).subs(q1r, 0)
    T1_r_offdiag = sp.simplify((q11 * T_1r_cov).subs(background))
    A_kh_static = sp.simplify(A_kh.subs(q1r, 0).subs(background))
    assert_zero(A_kh_static - A * B / (B - A * h_p**2), "[Hilbert] Khronon norm of Theta = t1 + h(r) minus A B/(B - A h'^2)")
    assert_zero(T1_r_offdiag - (-1 / A) * 2 * A_kh_static**2 * VA_sy * h_p, "[Hilbert] T^1_r minus manuscript form -(2/A) A_kh^2 d_A V h' (Eq. 23)")
    assert_zero(G_mixed[0, 2], "[metric-first] Off-diagonal Einstein component G^1_r of the static diagonal metric")
    sol_hp = sp.solve(T1_r_offdiag, h_p)
    assert_true(sol_hp == [0], "Theorem 3.1: G^1_r = T^1_r = 0 forces h'(r) = 0 wherever d_A V != 0 (Killing khronon, Eq. 23) [condition: d_A V != 0]", tag="D|H")

    # 0.6: Theorem 3.3(iii): PPN shift from the DERIVED G^r_r with V = 0, linear order in (m, b1, p) (Eq. 30)
    m_grav, p_scalar, b1_coeff, eps_bk = sp.symbols('m p b1 epsilon_bk', real=True)
    weak = {A: 1 - 2 * eps_bk * m_grav / r, B: 1 + 2 * eps_bk * b1_coeff / r, psi: eps_bk * p_scalar / r}
    Gr_r_lin = sp.simplify(sp.diff(Gr_r.subs(weak).doit(), eps_bk).subs(eps_bk, 0))
    b1_sol = sp.solve(Gr_r_lin, b1_coeff)[0]
    assert_equal(sp.simplify(b1_sol / m_grav), 1 - p_scalar / m_grav,
                 "Theorem 3.3(iii): linearised derived G^r_r = 0 gives gamma_PPN = b1/m (massless 1/r fiber charge, V = 0, Eq. 30)")

    # 0.7: Theorem 4.1: field equations E^A_A = G^A_A - T^A_A at omega = 0 and their normal form (Eqs. 33-39)
    T0 = [tc.subs(omega, 0) for tc in T_diag]
    E_11, E_22, E_rr, E_thth = G1_1 - T0[0], G2_2 - T0[1], Gr_r - T0[2], Gth_th - T0[3]

    dA_nf = sp.solve(E_rr, dA)[0]
    dA_paper = -2 * A * (r**2 * B * V_fn + 2 * r * dpsi - B + 1) / (r * (r * dpsi + 2))
    assert_zero(dA_nf - dA_paper, "[metric-first] Theorem 4.1: A'(r) solved from E^r_r = 0 minus manuscript Eq. (37)")

    ddA_from_dA = sp.diff(dA_nf, r)
    sys_B_psi = [sp.simplify(E_11.subs(ddA, ddA_from_dA).subs(dA, dA_nf)), sp.simplify(E_thth.subs(ddA, ddA_from_dA).subs(dA, dA_nf))]
    sol_B_psi = sp.solve(sys_B_psi, (dB, ddpsi))
    dB_nf, ddpsi_nf = sp.simplify(sol_B_psi[dB]), sp.simplify(sol_B_psi[ddpsi])

    dB_paper = (2 * B / (3 * r * (r * dpsi + 2))) * (
        r**3 * B * (2 * A * dV_dA + 2 * V_fn + dV_dpsi) * dpsi + r**2 * B * (4 * A * dV_dA + V_fn + 2 * dV_dpsi)
        + 3 * r**2 * dpsi**2 - 3 * r * (B - 1) * dpsi - 3 * (B - 1))
    ddpsi_paper = (1 / (3 * r)) * (
        r**2 * B * (2 * A * dV_dA + 2 * V_fn + dV_dpsi) * dpsi - 2 * r * B * (A * dV_dA + V_fn - dV_dpsi) - 3 * (B + 1) * dpsi)
    assert_zero(dB_nf - dB_paper, "[metric-first] Theorem 4.1: B'(r) solved from E^1_1 = E^theta_theta = 0 minus manuscript Eq. (38)")
    assert_zero(ddpsi_nf - ddpsi_paper, "[metric-first] Theorem 4.1: psi''(r) solved from E^1_1 = E^theta_theta = 0 minus manuscript Eq. (39)")

    ddA_explicit = sp.simplify(ddA_from_dA.subs(ddpsi, ddpsi_nf).subs(dB, dB_nf).subs(dA, dA_nf))
    on_shell = lambda e: sp.simplify(e.subs(ddA, ddA_explicit).subs(ddpsi, ddpsi_nf).subs(dB, dB_nf).subs(dA, dA_nf))
    assert_zero(on_shell(E_rr), "[metric-first] Residual E^r_r under the derived normal form (Eq. 33)")
    assert_zero(on_shell(E_11), "[metric-first] Residual E^1_1 under the derived normal form (Eq. 34)")
    assert_zero(on_shell(E_thth), "[metric-first] Residual E^theta_theta under the derived normal form (Eq. 35)")
    assert_zero(on_shell(E_22), "[metric-first] Residual E^2_2 under the derived normal form (Eq. 36, Bianchi closure: the 4th equation is not independent)")

    # 0.8: Mass term. (a) Linearise the DERIVED psi'' equation about the vacuum (A = B = 1, psi_t = 0, d_A V = 0) with
    #      V = (K/2) psi^2: the Yukawa operator u'' + (2/r) u' - mu^2 u fixes K in terms of the physical mass m_psi.
    K_s, eps_l, m_psi = sp.symbols('K epsilon_l m_psi', positive=True)
    u_f = sp.Function('u')(r)
    lin = ddpsi_nf.subs(dV_dA, 0).subs(dV_dpsi, K_s * psi).subs(V_fn, K_s * psi**2 / 2).subs(B, 1).subs(psi, eps_l * u_f).doit()
    lin = sp.expand(sp.diff(lin, eps_l).subs(eps_l, 0))
    mu2 = sp.simplify(lin.coeff(u_f))                                                       # u'' = mu2 u - (2/r) u'
    assert_zero(sp.simplify(lin - (mu2 * u_f - 2 * sp.diff(u_f, r) / r)), "Linearised Eq. (39): u'' - [mu^2 u - (2/r) u'] (flat-space Yukawa operator, nothing else survives)")
    jet_norm = sp.simplify(mu2 / K_s)                                                       # mu^2 = jet_norm * V''(0)
    assert_equal(jet_norm, sp.Rational(2, 3), "Linearised Eq. (39): mass^2 = (2/3) V''(0), i.e. the factor 1/(-kappa_psi) of Paper 0 (kappa_psi = -3/2) re-derived in the 5D frame")
    #      (b) 3x3 jet matrix on the W_3 basis (hypothesis H3): P(0) = 0, P'(0) = 0, (2/3) P''(0) = m_psi^2.
    Delta_psi = sp.Symbol('Delta_psi', real=True)
    w3_basis = [sp.exp(-2 * Delta_psi), sp.exp(-4 * Delta_psi), sp.exp(-6 * Delta_psi)]
    M_raw = sp.Matrix(3, 3, lambda a_i, b_i: sp.diff(w3_basis[b_i], (Delta_psi, a_i)).subs(Delta_psi, 0))
    M_jet = sp.diag(1, 1, jet_norm) * M_raw
    assert_equal(M_jet.det(), -sp.Rational(32, 3), "Paper 0 Thm 4.5(i): determinant of the 2-jet matrix on W_3 (unique solution)", tag="D|H")
    c_jet = M_jet.inv() * sp.Matrix([0, 0, m_psi**2])
    V_mass = sp.factor(sum(c_jet[i_c] * w3_basis[i_c] for i_c in range(3)))
    assert_zero(sp.simplify(V_mass - sp.Rational(3, 16) * m_psi**2 * sp.exp(-2 * Delta_psi) * (1 - sp.exp(-2 * Delta_psi))**2),
                "Paper 0 Thm 4.5(i): jet-matrix solution minus (3/16) m^2 e^(-2x) (1 - e^(-2x))^2 [basis W_3 = H3]", tag="D|H")
    jet2_V = sp.series(V_mass, Delta_psi, 0, 3).removeO()
    V2_coeff = sp.simplify(jet2_V / (m_psi**2 * Delta_psi**2))
    assert_equal(V2_coeff, sp.Rational(3, 4), "2-jet of the jet-matrix solution: V = c m^2 (psi - psi_t)^2 with c (Eq. 11) [basis W_3 and 2-jet truncation = H3]", tag="D|H")

    # 0.9: Einstein-frame null Ricci contraction (bridge to Paper 0 Thm 5.6(iii), Eq. 150): g~ = e^psi g4, radial null k.
    g4E = sp.exp(psi) * g4_mat
    geoE = Geometry(g4E, [t1_s, r, th, ph], sp.exp(2 * psi) * sp.sqrt(A * B) * r**2 * sp.sin(th))
    R_kk = geoE.Ric[0, 0] * B / A + geoE.Ric[1, 1]                                            # k^r = 1, (k^t)^2 = B/A
    F_E, H_E, R_ar = sp.exp(psi) * A, sp.exp(psi) * B, sp.exp(psi / 2) * r                    # g~_tt = -F_E, g~_rr = H_E, areal radius
    AEBE = F_E * H_E / sp.diff(R_ar, r)**2                                                    # A_E B_E in areal gauge
    focusing = (sp.diff(R_ar, r) / R_ar) * sp.diff(AEBE, r) / AEBE
    assert_zero(sp.simplify(R_kk - focusing), "[metric-first] Focusing identity R~_kk - (R'/R) d_r ln(A_E B_E), A_E B_E = e^psi A B/(1 + r psi'/2)^2 (kinematic)")
    nec_density = sp.Rational(3, 2) * dpsi**2 + 2 * A * B * dV_dA
    assert_zero(on_shell(R_kk) - nec_density,
                "R~_kk on the derived normal form minus [(3/2) psi'^2 + 2 A B d_A V]: Paper 0 Eq. (150) recovered with g~_rr = e^psi B, V_E = e^(-psi) V")
    Gkk_5D = B * (Gr_r - G1_1)
    assert_zero(on_shell(Gkk_5D) - 2 * A * B * dV_dA, "5D-frame null contraction G_kk = B (G^r_r - G^1_1) on shell minus 2 A B d_A V")

    # 0.10: Appendix A: 5D Painleve-Gullstrand inverse metric & 12 Christoffels (Eqs. 95-96)
    rs_s = sp.Symbol('r_s', positive=True)
    Phi_pg = sp.Function('Phi')(r)
    g_pg = sp.Matrix([
        [-(1 - rs_s / r), 0, sp.sqrt(rs_s / r), 0],
        [0, -Phi_pg**2, 0, 0],
        [sp.sqrt(rs_s / r), 0, 1, 0],
        [0, 0, 0, r**2]
    ])
    geo_pg = Geometry(g_pg, [t1_s, t2_s, r, ph])
    Gam_pg = geo_pg.Gamma
    assert_equal(sp.simplify(sp.det(g_pg)), Phi_pg**2 * r**2, "[metric-first] Lemma 2.9 & App. A: det(g_PG) == +Phi^2 det(gamma_ij) (Eqs. 14, 95)")
    pg_targets = [
        ("#1: Gamma^1_{11}", Gam_pg[0][0][0], +rs_s / (2 * r**2) * sp.sqrt(rs_s / r)),
        ("#2: Gamma^1_{1r}", Gam_pg[0][0][2], +rs_s / (2 * r**2)),
        ("#3: Gamma^1_{rr}", Gam_pg[0][2][2], +1 / (2 * r) * sp.sqrt(rs_s / r)),
        ("#4: Gamma^1_{phi phi}", Gam_pg[0][3][3], -r * sp.sqrt(rs_s / r)),
        ("#5: Gamma^1_{22}", Gam_pg[0][1][1], +sp.sqrt(rs_s / r) * Phi_pg * sp.diff(Phi_pg, r)),
        ("#6: Gamma^2_{2r}", Gam_pg[1][1][2], sp.diff(Phi_pg, r) / Phi_pg),
        ("#7: Gamma^r_{11}", Gam_pg[2][0][0], +rs_s * (r - rs_s) / (2 * r**3)),
        ("#8: Gamma^r_{1r}", Gam_pg[2][0][2], -rs_s / (2 * r**2) * sp.sqrt(rs_s / r)),
        ("#9: Gamma^r_{rr}", Gam_pg[2][2][2], -rs_s / (2 * r**2)),
        ("#10: Gamma^r_{phi phi}", Gam_pg[2][3][3], -(r - rs_s)),
        ("#11: Gamma^r_{22}", Gam_pg[2][1][1], +(1 - rs_s / r) * Phi_pg * sp.diff(Phi_pg, r)),
        ("#12: Gamma^phi_{r phi}", Gam_pg[3][2][3], 1 / r),
    ]
    for name_pg, got_pg, want_pg in pg_targets:
        assert_equal(got_pg, want_pg, f"[metric-first] App. A PG Christoffel {name_pg}")

    # 0.11: Export the derived objects (later modules consume these instead of re-typing them)
    r_n, A_n, B_n, dp_n, V_n, VP_n, VA_n = sp.symbols('r_n A_n B_n dp_n V_n VP_n VA_n', real=True)

    def to_numeric_symbols(expr):
        return expr.subs(dV_dpsi, VP_n).subs(dV_dA, VA_n).subs(V_fn, V_n).subs(dpsi, dp_n).subs({A: A_n, B: B_n}).subs(r, r_n)

    args_n = (r_n, A_n, B_n, dp_n, V_n, VP_n, VA_n)
    B_aux = sp.Symbol('B_aux', real=True)
    slope_bracket = sp.diff(ddpsi_nf.subs(B, B_aux), B_aux)                                  # coefficient of the 1/(r - r_h) pole of psi''
    assert_zero(sp.diff(ddpsi_nf.subs(B, B_aux), B_aux, 2), "Eq. (39) is affine in B: the horizon pole of psi'' is carried by a single bracket")
    slope_reg = sp.solve(slope_bracket, dpsi)[0]
    CTX["static"] = {
        "r": r, "A": A, "B": B, "psi": psi, "V_fn": V_fn, "dV_dpsi": dV_dpsi, "dV_dA": dV_dA, "omega": omega,
        "geo5": geo5, "T_mixed_omega": T_mixed_omega, "box5_psi": box5_psi, "Gr_r": Gr_r, "Gth_th": Gth_th,
        "dA_nf": dA_nf, "dB_nf": dB_nf, "ddpsi_nf": ddpsi_nf, "slope_reg": slope_reg,
    }
    CTX["nf_num"] = sp.lambdify(args_n, [to_numeric_symbols(e) for e in (dA_nf, dB_nf, ddpsi_nf)], "numpy")
    CTX["slope_num"] = sp.lambdify((r_n, A_n, V_n, VP_n, VA_n), to_numeric_symbols(slope_reg), "numpy")
    CTX["nec_num"] = sp.lambdify((A_n, B_n, dp_n, VA_n), to_numeric_symbols(nec_density), "numpy")
    CTX["V2_coeff"] = V2_coeff

    # 0.12: Cylinder condition H6.
    #  (a) Symmetric criticality on the static sector, by explicit variation: the reduced action
    #      S_red[A, B, psi] = int dr sqrt|g5| (R5 - 2V) has Euler-Lagrange equations equal to the 5D field equations.
    #      With delta(sqrt|g| R) = sqrt|g| G_AB delta g^{AB} and delta(sqrt|g| ell) = -sqrt|g| T_AB delta g^{AB}:
    #      EL_A = -sqrt|g| E^1_1 / A,  EL_B = -sqrt|g| E^r_r / B,  EL_psi = -2 sqrt|g| E^2_2.
    sq_red = geo5.sqrtg / (Phi_inf_s * sp.sin(th))
    L_red = sq_red * (geo5.R - 2 * V_fn)
    assert_zero(sp.simplify(euler_lagrange(L_red, A, r) / sq_red + E_11 / A),
                "[symmetric criticality] Static sector: EL_A[sqrt|g5|(R5 - 2V)]/sqrt|g5| + E^1_1/A (reduced action reproduces the (1,1) field equation)")
    assert_zero(sp.simplify(euler_lagrange(L_red, B, r) / sq_red + E_rr / B),
                "[symmetric criticality] Static sector: EL_B[sqrt|g5|(R5 - 2V)]/sqrt|g5| + E^r_r/B (reduced action reproduces the (r,r) field equation)")
    assert_zero(sp.simplify(euler_lagrange(L_red, psi, r) / sq_red + 2 * E_22),
                "[symmetric criticality] Static sector: EL_psi[sqrt|g5|(R5 - 2V)]/sqrt|g5| + 2 E^2_2 (reduced action reproduces the (2,2) field equation)")
    print("         (the remaining equation E^theta_theta follows from these three by the Bianchi closure verified in 0.7)")
    #  (b) Time-dependent spherically symmetric bundle metrics with a t1-r cross term: the mixed components G_{mu 2} vanish.
    A_t1r = sp.Function('A_tr')(t1_s, r)
    B_t1r = sp.Function('B_tr')(t1_s, r)
    C_t1r = sp.Function('C_tr')(t1_s, r)
    psi_t1r = sp.Function('psi_tr')(t1_s, r)
    g5_cyl = sp.Matrix([
        [-A_t1r, 0, C_t1r, 0, 0],
        [0, -Phi_inf_s**2 * sp.exp(2 * psi_t1r), 0, 0, 0],
        [C_t1r, 0, B_t1r, 0, 0],
        [0, 0, 0, r**2, 0],
        [0, 0, 0, 0, r**2 * sp.sin(th)**2]
    ])
    geo5_cyl = Geometry(g5_cyl, [t1_s, t2_s, r, th, ph])
    assert_zero(sp.Matrix([geo5_cyl.Ein[m_i, 1] for m_i in (0, 2, 3, 4)]),
                "[symmetric criticality] G_{mu 2} on the t2-independent, t2-reflection-even (t1, r) sector (the four mixed equations are empty there)")
    print("         Scope: (a) and Module 2.4 verify the reduction on the static and FLRW sectors by explicit variation; (b) covers the (t1, r) sector.")
    print("         For a general t2-independent metric the statement is Palais' theorem (compact isometry group), which is cited, not computed here.")

    #  (c) Node C: kinetic signs of the n >= 1 fiber tower (linearised 5D Einstein operator, unitary gauge)
    log("Node C: building the 15x15 linearised Einstein mode operator (a few seconds to a few minutes, depending on the SymPy version)...")
    E_kk, P_kk, Dv_kk, s_kk = _build_kk_mode_operators((-1, -1, 1, 1, 1), 1)
    log("Node C: operator built; checking gauge invariance, Bianchi identity and the quadratic form...")
    w_k, q_k, Phi0_k, kv_k = s_kk['w'], s_kk['q'], s_kk['Phi0'], s_kk['k']
    macro_k, n_a_k, eta_k = s_kk['macro'], s_kk['n_a'], s_kk['eta']
    keys_k = sorted(s_kk['a'])
    assert_zero(E_kk * P_kk, "[Node C] Gauge invariance E P == 0 of the 15x15 n >= 1 mode operator (Paper 0 THM #08)")
    assert_zero(Dv_kk * E_kk, "[Node C] Contracted linearised Bianchi identity Dv E == 0 of the 15x15 n >= 1 mode operator")
    det_stueck = sp.factor(P_kk[n_a_k:, :].det())
    assert_zero(sp.Abs(det_stueck) - 2 * q_k**5, "[Node C] Stueckelberg block |det| - 2 q^5: invertible for q != 0, so the unitary gauge b = c = 0 is reachable")
    FP_kk = E_kk[:n_a_k, :n_a_k]                                                # unitary gauge b = c = 0
    weight_kk = sp.diag(*[sp.Integer(1 if m == n else 2) / (eta_k[m, m] * eta_k[n, n]) for (m, n) in keys_k])
    WFP_kk = (weight_kk * FP_kk).applyfunc(sp.expand)
    assert_zero(WFP_kk - WFP_kk.T.subs({w_k: -w_k, kv_k[0]: -kv_k[0], kv_k[1]: -kv_k[1], kv_k[2]: -kv_k[2]}),
                "[Node C] Hermiticity of the quadratic form h^{AB} dG_AB on the n >= 1 mode space (E(-p)^T pairing)")

    kz_k = kv_k[2]
    along_z = {kv_k[0]: 0, kv_k[1]: 0}
    WFP_z = WFP_kk.subs(along_z).applyfunc(sp.expand)
    T1_k, X_k, Y_k, Z_k = macro_k
    k_cov = {T1_k: -w_k, X_k: 0, Y_k: 0, Z_k: kz_k}
    u_cov = {T1_k: -kz_k, X_k: 0, Y_k: 0, Z_k: w_k}
    x_cov = {T1_k: 0, X_k: 1, Y_k: 0, Z_k: 0}
    y_cov = {T1_k: 0, X_k: 0, Y_k: 1, Z_k: 0}
    u_sq = sum(u_cov[m]**2 / eta_k[m, m] for m in macro_k)                      # = w^2 - kz^2

    def _sym_tensor(p_c, q_c):
        Tm = sp.zeros(5, 5)
        for m in macro_k:
            for n in macro_k:
                Tm[m, n] = sp.Rational(1, 2) * (p_c[m] * q_c[n] + p_c[n] * q_c[m])
        return Tm

    def _amp_vec(eps_cov):
        return sp.Matrix([eps_cov[m, n] for (m, n) in keys_k])

    def _eta_dot(e1, e2):
        return sp.expand(sum(e1[m, n] * e2[m, n] / (eta_k[m, m] * eta_k[n, n]) for m in macro_k for n in macro_k))

    pol_kk = {
        "T1 = x(x)y": _sym_tensor(x_cov, y_cov),
        "T2 = (xx - yy)/2": (_sym_tensor(x_cov, x_cov) - _sym_tensor(y_cov, y_cov)) / 2,
        "V1 = u(x)x": _sym_tensor(u_cov, x_cov),
        "V2 = u(x)y": _sym_tensor(u_cov, y_cov),
        "S  = uu - (u.u)(xx + yy)/2": _sym_tensor(u_cov, u_cov) - u_sq * (_sym_tensor(x_cov, x_cov) + _sym_tensor(y_cov, y_cov)) / 2,
    }
    names_kk = list(pol_kk)
    for nm in names_kk:
        e_c = pol_kk[nm]
        assert_zero(sp.Matrix([sum(k_cov[m] / eta_k[m, m] * e_c[m, n] for m in macro_k) for n in macro_k]),
                    f"[Node C] Transversality k^mu eps_{{mu nu}} of {nm} (off shell)")
        assert_zero(sum(e_c[m, m] / eta_k[m, m] for m in macro_k), f"[Node C] Tracelessness of {nm}")

    vecs_kk = [_amp_vec(pol_kk[nm]) for nm in names_kk]
    rhs_vecs = [(WFP_z * v_i).applyfunc(sp.expand) for v_i in vecs_kk]
    p_sq_z = s_kk['p_sq'].subs(along_z)                                         # -w^2 + kz^2 - q^2/Phi0^2
    Q_kk = sp.Matrix(5, 5, lambda i, j: sp.expand(-sp.Rational(1, 2) * (vecs_kk[i].T * rhs_vecs[j])[0, 0]))
    Gram_kk = sp.Matrix(5, 5, lambda i, j: _eta_dot(pol_kk[names_kk[i]], pol_kk[names_kk[j]]))
    assert_zero(Gram_kk - sp.diag(*[Gram_kk[i, i] for i in range(5)]),
                "[Node C] The five TT polarisations are mutually orthogonal in the eta-norm")
    ratio_kk = sp.cancel(Q_kk[0, 0] / (p_sq_z * Gram_kk[0, 0]))
    assert_zero((Q_kk - ratio_kk * p_sq_z * Gram_kk).applyfunc(sp.expand),
                f"[Node C] Quadratic form on the TT space: Q(eps, eps') - ({ratio_kk}) p^2 (eps . eps'), p^2 = -w^2 + kz^2 - q^2/Phi0^2")
    assert_true(ratio_kk == -sp.Rational(1, 4),
                f"[Node C] Normalisation {ratio_kk} < 0: L2 = -(1/4) p^2 (eps.eps)|h|^2, i.e. +(1/4)(eps.eps) h_t^2 + ... (healthy sign when eps.eps > 0)")

    assert_zero(sp.simplify(A * B_stiff - P_paper),
                "Theorem 4.6: P = A B solved from derived G^r_r = 0 with psi = psi_t(A) minus Eq. (55) [stiff-limit hypothesis: V -> 0, psi -> psi_t(A)]", tag="D|H")
    P_prod = sp.Function('P')(r)
    dP_prod = sp.diff(P_prod, r)
    stiff_2AB_Gthth = sp.simplify(2 * A * B * S0["Gth_th"].subs(dB, B * (dP_prod / P_prod - dA / A)))

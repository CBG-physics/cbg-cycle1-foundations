class Geometry:
    """Levi-Civita geometry of an explicit (possibly non-diagonal) metric g on coordinates x."""
    def __init__(self, g, x, sqrtg=None):
        self.g, self.x, self.n = sp.Matrix(g), list(x), len(x)
        n, x = self.n, self.x
        self.ginv = self.g.inv()
        gi, g = self.ginv, self.g
        self.Gamma = [[[sp.simplify(sum(gi[c, d] * (sp.diff(g[d, a], x[b]) + sp.diff(g[d, b], x[a]) - sp.diff(g[a, b], x[d]))
                                        for d in range(n)) / 2) for b in range(n)] for a in range(n)] for c in range(n)]
        G = self.Gamma
        self.Riem = [[[[sp.diff(G[c][d][b], x[a]) - sp.diff(G[c][d][a], x[b]) +
                        sum(G[c][a][e] * G[e][d][b] - G[c][b][e] * G[e][d][a] for e in range(n))
                        for b in range(n)] for a in range(n)] for d in range(n)] for c in range(n)]
        self.Ric = sp.Matrix(n, n, lambda d, b: sp.simplify(sum(self.Riem[a][d][a][b] for a in range(n))))
        self.R = sp.simplify(sum(gi[a, b] * self.Ric[a, b] for a in range(n) for b in range(n)))
        self.Ein = sp.simplify(self.Ric - g * self.R / 2)
        self.sqrtg = sqrtg if sqrtg is not None else sp.sqrt(sp.Abs(g.det()))

    def box(self, f):
        n, x, gi, sq = self.n, self.x, self.ginv, self.sqrtg
        return sp.simplify(sum(sp.diff(sq * gi[a, b] * sp.diff(f, x[b]), x[a]) for a in range(n) for b in range(n)) / sq)

    def mixed(self, T):
        return sp.simplify(self.ginv * T)

    def div_mixed(self, T, b):
        """nabla_A T^A_b for a mixed tensor T^A_B given as a matrix (row = upper index)."""
        n, x, G = self.n, self.x, self.Gamma
        return sp.simplify(sum(sp.diff(T[a, b], x[a]) for a in range(n))
                           + sum(G[a][a][c] * T[c, b] for a in range(n) for c in range(n))
                           - sum(G[c][a][b] * T[a, c] for a in range(n) for c in range(n)))


def laplace_beltrami(G, x, sqrtG, f):
    """(1/sqrt|G|) d_i ( sqrt|G| G^{ij} d_j f ) for an explicit metric G (no curvature needed)."""
    Gi = sp.Matrix(G).inv()
    n = len(x)
    return sum(sp.diff(sqrtG * Gi[i, j] * sp.diff(f, x[j]), x[i]) for i in range(n) for j in range(n)) / sqrtG


def euler_lagrange(L, q, t):
    """Euler-Lagrange expression of L(q, q', q'') with respect to the function q(t)."""
    return sp.diff(L, q) - sp.diff(sp.diff(L, sp.diff(q, t)), t) + sp.diff(sp.diff(L, sp.diff(q, t, 2)), t, 2)


